    // connections — loopback INCLUDED. Windows Firewall exempts loopback
    // traffic, and the protocol-specific blocks below never covered
    // arbitrary ports, so a sandbox process could reach any host listener
    // on 127.0.0.1. These blanket blocks MUST stay first: the rest of the
